@Component({
  selector: 'app-icon',
  standalone: true,
  imports: [CommonModule],
  template: `
    <svg
      xmlns="http://www.w3.org/2000/svg"
      [attr.width]="size"
      [attr.height]="size"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      [attr.stroke-width]="strokeWidth"
      stroke-linecap="round"
      stroke-linejoin="round"
      [class]="computedClass"
      [innerHTML]="sanitizedSvg"
      aria-hidden="true"
    ></svg>
  `,
  styles: [`
    :host {
      display: inline-flex;
      align-items: center;
      justify-content: center;
      vertical-align: middle;
      line-height: 0;
      flex-shrink: 0;
    }
    svg {
      display: block;
      flex-shrink: 0;
      transition: stroke 0.15s ease, transform 0.15s ease;
    }
  `],
})
export class IconComponent {
  @Input() name: string = 'info';
  @Input() size: number = 18;
  @Input() strokeWidth: number = 2;
  @Input() class: string = '';

  constructor(private sanitizer: DomSanitizer) {}

  get sanitizedSvg(): SafeHtml {
    const key = (this.name || '').toLowerCase().trim();
    const svgPath = LUCIDE_ICONS[key] || LUCIDE_ICONS['info'];
    return this.sanitizer.bypassSecurityTrustHtml(svgPath);
  }

  get computedClass(): string {
    return `lucide-icon lucide-${this.name} ${this.class}`.trim();
  }
}
